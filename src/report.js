import { CATEGORIES, REQUIREMENTS, MANUAL_CHECKS } from './requirements.js';

const ICON = { pass: '✅', fail: '❌', warn: '⚠️', info: 'ℹ️', skip: '⏭️' };
const ORDER = { fail: 0, warn: 1, pass: 2, info: 3, skip: 4 };

export function summarize(results) {
  const counts = { pass: 0, fail: 0, warn: 0, info: 0, skip: 0 };
  for (const r of results) counts[r.status]++;
  return counts;
}

function grouped(results) {
  const byCat = new Map(Object.keys(CATEGORIES).map((c) => [c, []]));
  for (const r of results) byCat.get(REQUIREMENTS[r.requirement]?.category || 'transport').push(r);
  for (const list of byCat.values()) list.sort((a, b) => ORDER[a.status] - ORDER[b.status]);
  return byCat;
}

export function toJson({ target, source, results }) {
  return JSON.stringify({ tool: 'quickbooks-review-check', version: '0.1.0', generatedAt: new Date().toISOString(), target, source, summary: summarize(results), results, manualChecks: MANUAL_CHECKS.map((m) => ({ ...m, requirement: REQUIREMENTS[m.id].title })) }, null, 2);
}

export function toMarkdown({ target, source, results }) {
  const c = summarize(results);
  const verdict = c.fail ? `❌ **${c.fail} blocking issue${c.fail > 1 ? 's' : ''}** — Intuit would likely send this back.` : c.warn ? '⚠️ **No blocking issues**, but review the warnings before submitting.' : '✅ **All automated checks passed.**';
  const lines = [
    '# QuickBooks App Security Review — self-check',
    '',
    [target && `**App:** ${target}`, source && `**Source:** \`${source}\``].filter(Boolean).join(' · '),
    '',
    verdict,
    '',
    `| ✅ Pass | ❌ Fail | ⚠️ Warn | ⏭️ Skipped |`,
    `|---|---|---|---|`,
    `| ${c.pass} | ${c.fail} | ${c.warn} | ${c.skip} |`,
    '',
  ];
  for (const [cat, list] of grouped(results)) {
    if (!list.length) continue;
    lines.push(`## ${CATEGORIES[cat]}`, '');
    for (const r of list) {
      lines.push(`- ${ICON[r.status]} **${r.title}** — ${md(r.detail)}`);
      if (r.fix && (r.status === 'fail' || r.status === 'warn')) lines.push(`  - _Fix:_ ${r.fix}`);
      for (const l of r.locations || []) lines.push(`  - \`${l.file}:${l.line}\` ${l.snippet ? `— \`${l.snippet.replace(/`/g, "'")}\`` : ''}`);
    }
    lines.push('');
  }
  lines.push('## Manual attestation (Intuit will ask)', '', 'These cannot be proven by a scanner. Tick them off before you submit:', '');
  for (const m of MANUAL_CHECKS) lines.push(`- [ ] ${m.prompt}`);
  lines.push('', '---', '_Generated by [quickbooks-review-check](https://github.com/apideck-libraries/quickbooks-review-check), a free tool from [Apideck](https://www.apideck.com). Not affiliated with or endorsed by Intuit; passing these checks does not guarantee approval._');
  return lines.join('\n');
}

const md = (s) => String(s || '').replace(/\|/g, '\\|');

const color = (code) => (s) => (process.stdout.isTTY && !process.env.NO_COLOR ? `\x1b[${code}m${s}\x1b[0m` : s);
const C = { pass: color(32), fail: color(31), warn: color(33), info: color(36), skip: color(90), bold: color(1), dim: color(90) };
const TAG = { pass: 'PASS', fail: 'FAIL', warn: 'WARN', info: 'INFO', skip: 'SKIP' };

export function toConsole({ target, source, results }) {
  const out = [C.bold('QuickBooks App Security Review — self-check'), C.dim([target, source].filter(Boolean).join('  ·  ')), ''];
  for (const [cat, list] of grouped(results)) {
    if (!list.length) continue;
    out.push(C.bold(CATEGORIES[cat]));
    for (const r of list) {
      out.push(`  ${C[r.status](TAG[r.status].padEnd(4))}  ${r.title}`);
      if (r.status !== 'pass') out.push(C.dim(`        ${r.detail}`));
      if (r.fix && (r.status === 'fail' || r.status === 'warn')) out.push(`        → ${r.fix}`);
      for (const l of (r.locations || []).slice(0, 5)) out.push(C.dim(`        ${l.file}:${l.line}  ${l.snippet || ''}`));
      if ((r.locations || []).length > 5) out.push(C.dim(`        … ${r.locations.length - 5} more`));
    }
    out.push('');
  }
  const c = summarize(results);
  out.push(`${C.pass(`${c.pass} passed`)}  ${C.fail(`${c.fail} failed`)}  ${C.warn(`${c.warn} warnings`)}  ${C.skip(`${c.skip} skipped`)}`);
  out.push(C.dim(`Plus ${MANUAL_CHECKS.length} manual attestation items — run with --markdown to get the checklist.`));
  return out.join('\n');
}
